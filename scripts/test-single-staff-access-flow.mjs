import assert from "node:assert/strict";
import {existsSync, readFileSync} from "node:fs";
import {test} from "node:test";

const read=(file)=>readFileSync(file,"utf8");

test("no obsolete manual staff creator, duplicate client register or access review",()=>{
 for(const file of [
   "components/staff/staff-directory.tsx",
   "components/staff/access-review.tsx",
   "app/api/staff/directory/route.ts",
 ]) assert.equal(existsSync(file),false,file+" must stay removed");
 const legacyDirectory=read("app/dashboard/staff/directory/page.tsx");
 const legacyAccess=read("app/dashboard/staff/access/page.tsx");
 assert.match(legacyDirectory,/redirect\("\/dashboard\/staff#staff-access"\)/);
 assert.match(legacyAccess,/redirect\("\/dashboard\/staff#staff-access"\)/);
 for(const path of ["modules/platform/navigation/erp-operational-routes.ts",
                     "modules/platform/navigation/erp-route-registry.ts"]){
   const text=read(path);
   assert.doesNotMatch(text,/id:\s*"staff-directory"/);
   assert.doesNotMatch(text,/id:\s*"staff-access"/);
   assert.doesNotMatch(text,/"\/dashboard\/staff\/directory"/);
   assert.doesNotMatch(text,/"\/dashboard\/staff\/access"/);
 }
});

test("single request path and working in-app account guide preserve verified staff management",()=>{
 const main=read("app/dashboard/staff/page.tsx");
 const guide=read("app/dashboard/help/staff-access/page.tsx");
 const signin=read("app/sign-in/page.tsx");
 const publicRequest=read("app/request-access/page.tsx");
 assert.match(main,/href="\/dashboard\/help\/staff-access"/);
 assert.doesNotMatch(main,/sohoj-academy\/blob\/feature\/redesign_refactor/);
 assert.match(main,/href="\/dashboard\/staff#staff-access"/);
 assert.match(main,/requestsView=history/);
 assert.match(main,/AccessRequestRegister/);
 assert.match(main,/StaffRegister rows=\{rows\}/);
 assert.doesNotMatch(main,/components\/staff\/staff-directory/);
 assert.match(guide,/requirePermission\("system.users.manage"\)/);
 assert.match(guide,/Back to staff requests/);
 assert.match(guide,/Applicant requests access/);
 assert.match(guide,/Owner or administrator verifies/);
 assert.match(guide,/Applicant activates account/);
 assert.match(signin,/href="\/request-access"/);
 assert.match(publicRequest,/AccessRequestForm/);
});

